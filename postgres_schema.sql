-- Apply once to an empty Supabase project as its database owner.
-- The Flask app uses a privileged direct PostgreSQL connection; do not expose
-- DATABASE_URL, the database password, or a service-role key to the browser.

CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('resident', 'staff', 'admin')),
    office TEXT CHECK (office IN ('treasurer', 'secretary', 'bpso')),
    position TEXT,
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
    is_super_admin INTEGER NOT NULL DEFAULT 0,
    is_founding_admin INTEGER NOT NULL DEFAULT 0,
    must_reset_pw INTEGER NOT NULL DEFAULT 0,
    failed_logins INTEGER NOT NULL DEFAULT 0,
    locked_until TEXT,
    address TEXT,
    contact_number TEXT,
    created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')),
    created_by INTEGER,
    profile_picture TEXT,
    recovery_email TEXT
);

CREATE TABLE IF NOT EXISTS requests (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_no TEXT NOT NULL UNIQUE,
    resident_id INTEGER NOT NULL REFERENCES users(id),
    request_type TEXT NOT NULL,
    purpose TEXT,
    details TEXT,
    contact_number TEXT,
    request_address TEXT,
    civil_status TEXT,
    age INTEGER,
    computed_fee INTEGER,
    num_copies INTEGER NOT NULL DEFAULT 1,
    claiming_date TEXT,
    has_representative INTEGER NOT NULL DEFAULT 0,
    representative_name TEXT,
    representative_id_type TEXT,
    registered_voter INTEGER NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'Submitted'
        CHECK (status IN ('Submitted','Under Review','Processing','Approved','Rejected','Completed')),
    assigned_staff_id INTEGER REFERENCES users(id),
    remarks TEXT,
    created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')),
    updated_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS community_issues (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category TEXT NOT NULL,
    location TEXT NOT NULL,
    normalized_location TEXT NOT NULL,
    status TEXT NOT NULL
        CHECK (status IN ('Pending','Under Review','Scheduled','Resolved','Closed','Rejected')),
    created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')),
    updated_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS complaints (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_no TEXT NOT NULL UNIQUE,
    resident_id INTEGER NOT NULL REFERENCES users(id),
    category TEXT NOT NULL,
    description TEXT NOT NULL,
    location TEXT,
    priority TEXT NOT NULL DEFAULT 'Normal' CHECK (priority IN ('High','Normal')),
    priority_reason TEXT,
    priority_is_manual INTEGER NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'Pending'
        CHECK (status IN ('Pending','Under Review','Scheduled','Resolved','Closed','Rejected')),
    assigned_staff_id INTEGER REFERENCES users(id),
    remarks TEXT,
    community_issue_id INTEGER REFERENCES community_issues(id),
    is_verified INTEGER NOT NULL DEFAULT 0,
    verified_by INTEGER REFERENCES users(id),
    verified_at TEXT,
    created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')),
    updated_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS request_files (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id INTEGER NOT NULL REFERENCES requests(id),
    file_type TEXT NOT NULL DEFAULT 'supporting_document'
        CHECK (file_type IN ('valid_id','authorization_letter','representative_id','supporting_document')),
    label TEXT,
    filename TEXT NOT NULL,
    stored_name TEXT NOT NULL,
    uploaded_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS community_issue_updates (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    community_issue_id INTEGER NOT NULL REFERENCES community_issues(id) ON DELETE CASCADE,
    status TEXT NOT NULL
        CHECK (status IN ('Pending','Under Review','Scheduled','Resolved','Closed','Rejected')),
    changed_by TEXT,
    message TEXT,
    created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS community_issue_follows (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    community_issue_id INTEGER NOT NULL REFERENCES community_issues(id) ON DELETE CASCADE,
    created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')),
    UNIQUE(user_id, community_issue_id)
);

CREATE TABLE IF NOT EXISTS complaint_files (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id INTEGER NOT NULL REFERENCES complaints(id),
    filename TEXT NOT NULL,
    stored_name TEXT NOT NULL,
    uploaded_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS notifications (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id),
    message TEXT NOT NULL,
    link TEXT,
    is_read INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS audit_logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id INTEGER REFERENCES users(id),
    actor_name TEXT,
    action TEXT NOT NULL,
    target TEXT,
    details TEXT,
    created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS chat_messages (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id),
    role TEXT NOT NULL CHECK (role IN ('user','assistant')),
    message TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value TEXT,
    updated_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS admin_chart_preferences (
    admin_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    analytics_type TEXT NOT NULL CHECK (analytics_type IN ('complaints','document-requests')),
    category TEXT NOT NULL,
    color TEXT NOT NULL CHECK (color ~ '^#[0-9A-Fa-f]{6}$'),
    updated_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')),
    PRIMARY KEY (admin_id, analytics_type, category)
);

CREATE TABLE IF NOT EXISTS status_history (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type TEXT NOT NULL CHECK (entity_type IN ('request','complaint')),
    entity_id INTEGER NOT NULL,
    status TEXT NOT NULL,
    changed_by_name TEXT,
    remarks TEXT,
    created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash TEXT NOT NULL UNIQUE,
    expires_at TEXT NOT NULL,
    used_at TEXT,
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS password_reset_codes (
    user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    code_hash TEXT,
    expires_at TEXT NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    used_at TEXT,
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS password_reset_limits (
    user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    last_sent_at TEXT,
    window_started_at TEXT,
    sends_in_window INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS admin_otp_challenges (
    user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    email_otp_hash TEXT,
    mode TEXT NOT NULL DEFAULT 'email_only',
    expires_at TEXT,
    sent_at TEXT,
    attempts INTEGER NOT NULL DEFAULT 0,
    window_started_at TEXT,
    sends_in_window INTEGER NOT NULL DEFAULT 0,
    used_at TEXT
);

CREATE TABLE IF NOT EXISTS resident_concern_allowances (
    user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    remaining INTEGER NOT NULL DEFAULT 5 CHECK (remaining BETWEEN 0 AND 5),
    total_submitted INTEGER NOT NULL DEFAULT 0,
    cooldown_started_at TEXT,
    cooldown_expires_at TEXT
);

CREATE TABLE IF NOT EXISTS concern_allowance_events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    complaint_id INTEGER REFERENCES complaints(id) ON DELETE CASCADE,
    event_type TEXT NOT NULL CHECK (event_type IN ('submitted','resolved_restoration','cooldown_refill')),
    slots INTEGER NOT NULL,
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS announcements (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    message TEXT NOT NULL,
    posted_by_name TEXT,
    created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_users_single_founding_admin
    ON users(is_founding_admin) WHERE role='admin' AND is_founding_admin=1;
CREATE INDEX IF NOT EXISTS idx_requests_resident ON requests(resident_id);
CREATE INDEX IF NOT EXISTS idx_requests_status ON requests(status);
CREATE INDEX IF NOT EXISTS idx_requests_created_type_status ON requests(created_at, request_type, status);
CREATE INDEX IF NOT EXISTS idx_complaints_resident ON complaints(resident_id);
CREATE INDEX IF NOT EXISTS idx_complaints_status ON complaints(status);
CREATE INDEX IF NOT EXISTS idx_complaints_created_category_status ON complaints(created_at, category, status);
CREATE INDEX IF NOT EXISTS idx_complaints_community_issue ON complaints(community_issue_id);
CREATE INDEX IF NOT EXISTS idx_complaints_verification ON complaints(community_issue_id, is_verified);
CREATE INDEX IF NOT EXISTS idx_notifications_user ON notifications(user_id);
CREATE INDEX IF NOT EXISTS idx_community_issue_follows_issue ON community_issue_follows(community_issue_id);
CREATE INDEX IF NOT EXISTS idx_status_history_entity ON status_history(entity_type, entity_id);
CREATE INDEX IF NOT EXISTS idx_password_reset_tokens_user ON password_reset_tokens(user_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_concern_allowance_event_once
    ON concern_allowance_events(complaint_id, event_type) WHERE complaint_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_community_issues_active_key
    ON community_issues(category, normalized_location)
    WHERE status IN ('Pending','Under Review','Scheduled');

DO $$
DECLARE
    table_name TEXT;
BEGIN
    FOREACH table_name IN ARRAY ARRAY[
        'users', 'requests', 'community_issues', 'complaints', 'request_files',
        'community_issue_updates', 'community_issue_follows', 'complaint_files',
        'notifications', 'audit_logs', 'chat_messages', 'settings',
        'admin_chart_preferences', 'status_history', 'password_reset_tokens',
        'password_reset_codes', 'password_reset_limits', 'admin_otp_challenges',
        'resident_concern_allowances', 'concern_allowance_events', 'announcements'
    ]
    LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', table_name);
    END LOOP;
END
$$;

REVOKE ALL ON TABLE
    public.users, public.requests, public.community_issues, public.complaints,
    public.request_files, public.community_issue_updates, public.community_issue_follows,
    public.complaint_files, public.notifications, public.audit_logs, public.chat_messages,
    public.settings, public.admin_chart_preferences, public.status_history,
    public.password_reset_tokens, public.password_reset_codes, public.password_reset_limits,
    public.admin_otp_challenges, public.resident_concern_allowances,
    public.concern_allowance_events, public.announcements
FROM anon, authenticated;
REVOKE ALL ON SEQUENCE
    public.users_id_seq, public.requests_id_seq, public.community_issues_id_seq,
    public.complaints_id_seq, public.request_files_id_seq,
    public.community_issue_updates_id_seq, public.community_issue_follows_id_seq,
    public.complaint_files_id_seq, public.notifications_id_seq, public.audit_logs_id_seq,
    public.chat_messages_id_seq, public.status_history_id_seq,
    public.password_reset_tokens_id_seq, public.concern_allowance_events_id_seq,
    public.announcements_id_seq
FROM anon, authenticated;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    REVOKE ALL ON TABLES FROM anon, authenticated;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    REVOKE ALL ON SEQUENCES FROM anon, authenticated;
